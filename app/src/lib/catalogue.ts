export function findCatalogueTopic(
  id: string,
): { category: CatalogueCategory; topic: CatalogueTopic } | undefined {
  for (const category of CATALOGUE) {
    const topic = category.topics.find((t) => t.id === id);
    if (topic) return { category, topic };
  }
  return undefined;
}

export const POPULAR_TOPICS: CatalogueTopic[] = CATALOGUE.flatMap((c) =>
  c.topics.filter((t) => t.popular === true),
);
